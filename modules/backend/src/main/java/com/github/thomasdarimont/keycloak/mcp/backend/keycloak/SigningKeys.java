package com.github.thomasdarimont.keycloak.mcp.backend.keycloak;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.locks.ReentrantLock;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Inject;

import org.jboss.logging.Logger;

import com.github.thomasdarimont.keycloak.mcp.backend.spi.Extensions;
import com.github.thomasdarimont.keycloak.mcp.config.McpServerConfig;
import com.github.thomasdarimont.keycloak.mcp.keycloak.DefaultSigningKeyGenerator;
import com.github.thomasdarimont.keycloak.mcp.keycloak.KeyVault;
import com.github.thomasdarimont.keycloak.mcp.keycloak.KeycloakSystem;
import com.github.thomasdarimont.keycloak.mcp.keycloak.SigningKey;
import com.github.thomasdarimont.keycloak.mcp.keycloak.SigningKeyGenerator;
import com.github.thomasdarimont.keycloak.mcp.spi.Extension;

import io.vertx.core.json.JsonArray;
import io.vertx.core.json.JsonObject;

/**
 * The {@code private_key_jwt} signing keys. A configured key ({@code kc-mcp.jwt.key-file}
 * or {@code keystore-file}) serves every system; without one, each system signs with its
 * own key from the {@link KeyVault} (a registered one, else the read-only
 * {@link FileKeyVault} with provisioned PEM files), created on first use only when the
 * vault can create keys, and published at {@code /auth/keys/<system>/jwks.json}.
 * <p>
 * Several instances of the server may share one vault (the database). The signer of a
 * system is therefore checked against the vault whenever a token is requested (one
 * indexed read per token request), so a key rotated on another instance is signed with
 * here within a token lifetime, and the JWKS is built from what the vault
 * {@link KeyVault#publishedSigningKeys publishes}, the current key and the recently
 * retired ones, never from this instance's cache, so Keycloak accepts assertions from
 * instances that have not caught up yet.
 */
@ApplicationScoped
public class SigningKeys {

    private static final Logger LOG = Logger.getLogger(SigningKeys.class);

    private final McpServerConfig config;
    private final KeyVault vault;
    private final SigningKeyGenerator generator;
    private final ReentrantLock lock = new ReentrantLock();
    private volatile JwtSigner configured;
    private final Map<String, JwtSigner> perSystem = new ConcurrentHashMap<>();
    private final Map<String, ReentrantLock> perSystemLocks = new ConcurrentHashMap<>();

    @Inject
    public SigningKeys(McpServerConfig config, Extensions extensions) {
        this(config, vault(config, extensions), generator(config, extensions));
    }

    public SigningKeys(McpServerConfig config, KeyVault vault) {
        this(config, vault, new DefaultSigningKeyGenerator(config.jwt().keySize()));
    }

    /** @param generator handed to the vault for the keys it creates */
    public SigningKeys(McpServerConfig config, KeyVault vault, SigningKeyGenerator generator) {
        this.config = config;
        this.vault = vault;
        this.generator = generator;
        vault.useSigningKeyGenerator(generator);
    }

    /** What a creating vault generates keys with. */
    public SigningKeyGenerator generator() {
        return generator;
    }

    /**
     * The registered vault with the lowest order, else the file vault under
     * {@code kc-mcp.keys-dir}.
     */
    static KeyVault vault(McpServerConfig config, Extensions extensions) {
        List<KeyVault> found = new ArrayList<>();
        for (KeyVault v : extensions.discover(KeyVault.class)) {
            if (extensions.admit(v, "KeyVault", config)) {
                found.add(v);
            }
        }
        found.sort(Comparator.comparingInt(Extension::order).thenComparing(Extension::id));
        if (!found.isEmpty()) {
            LOG.infof("Signing keys kept by %s", found.get(0).id());
            return found.get(0);
        }
        return new FileKeyVault(Extensions.resolve(config.keysDir()), config.jwt().algorithm());
    }

    /**
     * The registered generator with the lowest order, else the JDK one with
     * {@code kc-mcp.jwt.key-size}.
     */
    static SigningKeyGenerator generator(McpServerConfig config, Extensions extensions) {
        List<SigningKeyGenerator> found = new ArrayList<>();
        for (SigningKeyGenerator g : extensions.discover(SigningKeyGenerator.class)) {
            if (extensions.admit(g, "SigningKeyGenerator", config)) {
                found.add(g);
            }
        }
        found.sort(Comparator.comparingInt(Extension::order).thenComparing(Extension::id));
        if (!found.isEmpty()) {
            LOG.infof("Signing keys generated by %s", found.get(0).id());
            return found.get(0);
        }
        return new DefaultSigningKeyGenerator(config.jwt().keySize());
    }

    /** Whether one configured key serves every system. */
    public boolean configuredKey() {
        return config.jwt().keyFile().isPresent() || config.jwt().keystoreFile().isPresent();
    }

    public int assertionLifespan() {
        return config.jwt().assertionLifespan();
    }

    /**
     * The scope token requests ask for ({@code kc-mcp.admin-api-scope}), {@code null} for
     * none.
     */
    public String adminApiScope() {
        String scope = config.adminApiScope();
        return scope == null || scope.isBlank() ? null : scope.trim();
    }

    public KeyVault vault() {
        return vault;
    }

    /**
     * The signer for a system: the configured key, else the system's own current key from
     * the vault, which is read again on every call (a token request) so a rotation done
     * by another instance is picked up; the signer object is reused while the key is the
     * same. Callers that sign repeatedly hold a {@code Supplier} on this method, not the
     * result.
     */
    public JwtSigner signerFor(KeycloakSystem system) {
        if (configuredKey()) {
            return configured();
        }
        String name = system.name();
        SigningKey key = resolve(vault, name).orElseThrow(() -> new IllegalStateException(
                "[" + name + "] no private_key_jwt signing key in the read-only KeyVault '" + vault.id()
                        + "': provision one for this system (or use a vault that can create keys)"));
        JwtSigner cached = perSystem.get(name);
        if (cached != null && sameKey(cached, key)) {
            return cached;
        }
        ReentrantLock l = perSystemLocks.computeIfAbsent(name, n -> new ReentrantLock());
        l.lock();
        try {
            cached = perSystem.get(name);
            if (cached != null && sameKey(cached, key)) {
                return cached;
            }
            JwtSigner signer = new JwtSigner(key.privateKey(), key.publicKey(), key.algorithm(), key.keyId());
            perSystem.put(name, signer);
            LOG.infof("[%s] private_key_jwt key %s from %s%s", name, signer.jwk().getString("kid"), vault.id(),
                    cached == null ? "" : " (rotated elsewhere, previous kid " + cached.jwk().getString("kid") + ")");
            return signer;
        }
        finally {
            l.unlock();
        }
    }

    private static boolean sameKey(JwtSigner signer, SigningKey key) {
        return signer.algorithm().equals(key.algorithm())
                && Arrays.equals(signer.publicKey().getEncoded(), key.publicKey().getEncoded());
    }

    /**
     * The JWK Set of a system: the configured key, else what the vault publishes (the
     * current key and recently retired ones, created on first use by a creating vault);
     * empty when the vault is read-only and has no key for the system.
     */
    public Optional<JsonObject> jwksFor(KeycloakSystem system) {
        if (configuredKey()) {
            return Optional.of(jwks(configured()));
        }
        List<SigningKey> published = vault.publishedSigningKeys(system.name());
        if (published.isEmpty()) {
            if (resolve(vault, system.name()).isEmpty()) {
                return Optional.empty();
            }
            published = vault.publishedSigningKeys(system.name());
        }
        JsonArray keys = new JsonArray();
        for (SigningKey key : published) {
            keys.add(Jwks.jwk(key.publicKey(), key.algorithm(), key.keyId()));
        }
        return Optional.of(new JsonObject().put("keys", keys));
    }

    /**
     * The key of a system from a vault: the stored one, else a new one when the vault can
     * create keys, else empty (read-only vault without a provisioned key).
     */
    static Optional<SigningKey> resolve(KeyVault vault, String system) {
        Optional<SigningKey> found = vault.findSigningKey(system);
        if (found.isPresent() || !vault.supportsKeyCreation()) {
            return found;
        }
        return Optional.of(vault.createSigningKey(system));
    }

    /**
     * The current key of a system from the vault without creating one; empty for a system
     * without a key (and always when one configured key serves every system).
     */
    public Optional<SigningKey> currentKey(String system) {
        return configuredKey() ? Optional.empty() : vault.findSigningKey(system);
    }

    /**
     * Creates a new key for a system in the vault, retiring the current one, and signs
     * with it from now on; the JWKS gains the new key and keeps the retired one for the
     * vault's grace period, Keycloak fetches it again on the unknown kid. Other instances
     * sign with the new key from their next token request.
     *
     * @throws UnsupportedOperationException when the vault is read-only or one configured
     * key serves every system
     */
    public SigningKey rotate(String system) {
        if (configuredKey()) {
            throw new UnsupportedOperationException("One configured key (kc-mcp.jwt.key-file) serves every system");
        }
        if (!vault.supportsKeyCreation()) {
            throw new UnsupportedOperationException(
                    "KeyVault '" + vault.id() + "' is read-only: provision the new key for '" + system + "' there");
        }
        SigningKey key = vault.createSigningKey(system);
        perSystem.put(system, new JwtSigner(key.privateKey(), key.publicKey(), key.algorithm(), key.keyId()));
        LOG.infof("[%s] private_key_jwt key rotated in %s", system, vault.id());
        return key;
    }

    /** Drops the cached signer of a removed system; its key stays in the vault. */
    public void forget(String system) {
        perSystem.remove(system);
        perSystemLocks.remove(system);
    }

    /** The JWK Set of the configured key; empty when every system has its own. */
    public Optional<JsonObject> configuredJwks() {
        return configuredKey() ? Optional.of(jwks(configured())) : Optional.empty();
    }

    private JwtSigner configured() {
        JwtSigner s = configured;
        if (s != null) {
            return s;
        }
        lock.lock();
        try {
            if (configured == null) {
                configured = JwtSigner.fromConfig(config.jwt());
            }
            return configured;
        }
        finally {
            lock.unlock();
        }
    }

    private static JsonObject jwks(JwtSigner signer) {
        return new JsonObject().put("keys", new JsonArray().add(signer.jwk()));
    }
}
